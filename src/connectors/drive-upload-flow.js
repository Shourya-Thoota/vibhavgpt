// "Add it to my Google Drive": turn that sentence into one resolved, approvable upload, or say plainly why it can't be done yet.
//
// The steps, in order, each ending in a truthful answer rather than a guess:
//   1. Is Drive connected, turned on, and allowed to create files?      If not: the specific thing to fix.
//   2. Which file is "it"?  The newest document this conversation made. If it has gone from storage: say so and offer to make it again.
//   3. Which folder?  None named means the top of My Drive. A named folder is looked up: one match is used, none or several is a question.
//   4. Prepare the approval for exactly that file, folder and account. Nothing is uploaded here, and nothing is created: the person
//      approves the card, and only then does connectors/service.js perform the upload.
// No new document is generated by any step, and nothing is reported as uploaded by this module.

import { accountReference } from "./account-reference.js";
import { checkComposioFilesAccess, executeComposioTool } from "./composio-adapter.js";
import { driveWriteAllowedByScopes } from "./permission-coverage.js";
import { connectorNeedsReconnect, connectorNeedsVerification, createPendingAction, getConnectorAccountId, getEnabledConnectorGrant, publicConnectorMetadata } from "./service.js";
import {
  artifactSha256, chooseDriveFolder, describeArtifact, findLatestArtifact, folderQuestion, foldersFromResult, isTextArtifact, loadArtifactForUpload, parseDriveFolderPhrase,
} from "./drive-artifact.js";
import { fileNameFromDriveRequest } from "./drive-upload.js";

export { accountReference };

const notice = (content) => ({ kind: "connector_notice", content });
const clarification = (content) => ({ kind: "clarification", content });

/** The state of Drive for this person, as one thing they can act on. Null when Drive is ready to write. */
export async function driveBlocker(userId, deps = {}) {
  const grantFor = deps.getEnabledConnectorGrant ?? getEnabledConnectorGrant;
  const needsReconnect = deps.connectorNeedsReconnect ?? connectorNeedsReconnect;
  const grant = await grantFor(userId, "googledrive");
  if (!grant) {
    if (await needsReconnect(userId, "googledrive")) {
      return notice("Google Drive needs to be reconnected: its sign-in expired or was removed. Reconnect it in Extensions > Connectors, then ask again. Nothing was uploaded.");
    }
    if (await (deps.connectorNeedsVerification ?? connectorNeedsVerification)(userId, "googledrive")) {
      return notice("Google Drive's connection needs secure verification before it can be used, so nothing was uploaded. Reconnect it in Extensions to confirm it's yours.");
    }
    return notice("Google Drive isn't connected, or it is turned off. Connect or turn it on in Extensions > Connectors, then ask again. Nothing was uploaded.");
  }
  if (!driveWriteAllowedByScopes(grant.scopes || []).ok) {
    return notice("Google Drive is connected, but this account can only read files. Reconnect Google Drive and allow file creation, then ask again. Nothing was uploaded.");
  }
  return null;
}

/**
 * Prepares the approval for uploading this conversation's newest generated file. Returns:
 *   null                               there is no generated file in this conversation (the caller may use its text-upload path)
 *   { kind: "connector_notice" }       Drive can't be written to yet, with the one thing to fix
 *   { kind: "clarification" }          a question: the file is gone, or the folder is missing or ambiguous
 *   { kind: "pending_approval" }       the card to approve; carries the resolved file, folder and account
 */
export async function prepareDriveArtifactUpload({ userId, conversationId, requestText = "" }, deps = {}) {
  const findArtifact = deps.findLatestArtifact ?? findLatestArtifact;
  const artifact = await findArtifact(userId, conversationId);
  if (!artifact) return null;

  const blocked = await driveBlocker(userId, deps);
  if (blocked) return blocked;

  const loaded = await (deps.loadArtifactForUpload ?? loadArtifactForUpload)(userId, artifact.id);
  if (!loaded.ok) return clarification(loaded.message);

  // A binary file needs the file service to accept our credential. If it will not, say so now, before anyone is asked to approve an upload that
  // cannot work. The check carries nothing about the file (see checkComposioFilesAccess); the upload slot is only requested after approval.
  if (!isTextArtifact(artifact.mimeType)) {
    const access = await (deps.checkFilesAccess ?? checkComposioFilesAccess)();
    // Only a refusal of our credential stops the card. A timeout, a 429 or a 5xx says nothing about the credential, and the upload itself reports
    // its own failure truthfully if it cannot work.
    if (!access.ok && !access.transient) {
      console.warn(JSON.stringify({ event: "drive_file_service_unavailable", httpStatus: access.httpStatus ?? null }));
      return notice("I can't upload a PDF, Word or other non-text file to Google Drive from chat right now, so I haven't prepared anything and nothing was uploaded. Text, Markdown, CSV and JSON files can still be uploaded. Your document is still here to download.");
    }
  }

  const grant = await (deps.getEnabledConnectorGrant ?? getEnabledConnectorGrant)(userId, "googledrive");
  const accountId = await (deps.getConnectorAccountId ?? getConnectorAccountId)(userId, "googledrive").catch(() => null);
  if (!accountId) return notice("Google Drive isn't connected to an account that is verified for you, so I haven't prepared anything and nothing was uploaded. Reconnect Google Drive in Extensions, or ask the owner to verify the connection.");
  // A name or email a person recognises, never the connection's internal alias.
  const publicAccount = publicConnectorMetadata(grant?.metadata);
  const accountLabel = String(publicAccount.accountLabel || publicAccount.email || "").slice(0, 80) || null;

  let folder = null;
  const folderName = parseDriveFolderPhrase(requestText);
  if (folderName) {
    let outcome;
    try {
      const response = await (deps.executeComposioTool ?? executeComposioTool)({
        userId,
        toolSlug: "GOOGLEDRIVE_FIND_FOLDER",
        parameters: { name_contains: folderName, page_size: 25 },
        connectedAccountId: accountId,
      });
      outcome = chooseDriveFolder(folderName, foldersFromResult(response?.data));
    } catch {
      return clarification(`I couldn't look up your Google Drive folders just now, so I haven't prepared anything and nothing was uploaded. Try again in a moment, or say “My Drive” to put it at the top level.`);
    }
    if (outcome.kind !== "found") return clarification(folderQuestion(folderName, outcome));
    folder = outcome.folder;
  }

  const fileName = fileNameFromDriveRequest(requestText) || artifact.originalName;
  const destination = folder ? `“${folder.name}”` : "My Drive";
  const pending = await (deps.createPendingAction ?? createPendingAction)({
    userId,
    conversationId,
    toolName: "google_drive_upload_file",
    actionDescription: `Upload “${fileName}” (${describeArtifact(artifact)}) to Google Drive: ${destination}${accountLabel ? `, ${accountLabel}` : ""}`,
    payload: {
      fileName,
      attachmentId: artifact.id,
      mimeType: artifact.mimeType,
      sizeBytes: artifact.sizeBytes,
      sha256: artifactSha256(loaded.buffer),
      folderName: folder ? folder.name : "My Drive",
      ...(folder ? { folderId: folder.id } : {}),
      ...(accountLabel ? { accountLabel } : {}),
      // An opaque reference to the connected account this was prepared for. The approval only runs against that same account, and the internal alias
      // itself is never put in the card.
      ...(accountId ? { accountRef: accountReference(accountId) } : {}),
    },
  });
  return { kind: "pending_approval", pendingAction: pending, artifactName: fileName, destination, accountLabel };
}
